// 写真の id が、段の photos の形に合うか（* は何でも合う）
export function matches(pattern, id) {
  const rx = new RegExp('^' + pattern.split('*').map((s) => s.replace(/[.+?^${}()|[\]\\]/g, '\\$&')).join('.*') + '$');
  return rx.test(id);
}
